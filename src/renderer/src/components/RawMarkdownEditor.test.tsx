import { EditorView } from '@codemirror/view'
import { fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { describe, expect, it, vi } from 'vitest'
import { RawMarkdownEditor } from './RawMarkdownEditor'

describe('RawMarkdownEditor (CodeMirror 6)', () => {
  it('mounts CodeMirror 6 with markdown syntax highlighting and theme sync', () => {
    const { container } = render(
      <RawMarkdownEditor
        content={'# Title\n\n**Bold** and `code`'}
        language="markdown"
        theme="dark"
        cursor={{ selectionStart: 0, selectionEnd: 0 }}
        scrollTop={0}
        onChangeContent={vi.fn()}
        onUpdateViewState={vi.fn()}
      />
    )

    const cmEditor = container.querySelector('.cm-editor')
    expect(cmEditor).not.toBeNull()
    expect(cmEditor?.getAttribute('data-theme-mode')).toBe('dark')

    const contentEl = screen.getByTestId('document-editor')
    expect(contentEl).toHaveAttribute('contenteditable', 'true')
    expect(contentEl.textContent).toContain('# Title')
    expect(contentEl.textContent).toContain('**Bold**')

    // Syntax highlight spans are generated by @codemirror/lang-markdown + HighlightStyle
    const highlightedHeading = container.querySelector('.cm-line span')
    expect(highlightedHeading).not.toBeNull()
  })

  it('uses virtual scrolling viewport for 10,000+ line documents instead of mounting all lines in DOM', () => {
    const lines = Array.from({ length: 12000 }, (_, i) => `Line ${i + 1}: # Heading or text`)
    const hugeMarkdown = lines.join('\n')

    const { container } = render(
      <RawMarkdownEditor
        content={hugeMarkdown}
        language="markdown"
        theme="light"
        cursor={{ selectionStart: 0, selectionEnd: 0 }}
        scrollTop={0}
        onChangeContent={vi.fn()}
        onUpdateViewState={vi.fn()}
      />
    )

    const renderedLines = container.querySelectorAll('.cm-line')
    expect(renderedLines.length).toBeGreaterThan(0)
    expect(renderedLines.length).toBeLessThan(1000)
  })

  it('restores cursor selection and scrollTop and preserves unfocused selection on external sync', () => {
    const onUpdateViewState = vi.fn()
    const { container, rerender } = render(
      <RawMarkdownEditor
        content={'Hello World!\nSecond line'}
        language="markdown"
        theme="light"
        cursor={{ selectionStart: 2, selectionEnd: 5 }}
        scrollTop={120}
        onChangeContent={vi.fn()}
        onUpdateViewState={onUpdateViewState}
      />
    )

    const scroller = container.querySelector('.cm-scroller') as HTMLElement
    expect(scroller).not.toBeNull()
    expect(scroller.scrollTop).toBe(120)

    const contentEl = screen.getByTestId('document-editor')
    expect(contentEl.getAttribute('data-selection-start')).toBe('2')
    expect(contentEl.getAttribute('data-selection-end')).toBe('5')

    // External content sync from another pane updates doc without calling onUpdateViewState spuriously or wiping cursor
    rerender(
      <RawMarkdownEditor
        content={'Hello World!\nSecond line updated'}
        language="markdown"
        theme="light"
        cursor={{ selectionStart: 2, selectionEnd: 5 }}
        scrollTop={120}
        onChangeContent={vi.fn()}
        onUpdateViewState={onUpdateViewState}
      />
    )

    expect(contentEl.textContent).toContain('Second line updated')
    expect(contentEl.getAttribute('data-selection-start')).toBe('2')
    expect(contentEl.getAttribute('data-selection-end')).toBe('5')
    expect(scroller.scrollTop).toBe(120)

    // Scrolling updates scrollTop
    scroller.scrollTop = 240
    fireEvent.scroll(scroller)
    expect(onUpdateViewState).toHaveBeenCalledWith({ scrollTop: 240 })
  })

  it('captures typing edits through CodeMirror contenteditable input in jsdom', async () => {
    const user = userEvent.setup()
    const onChangeContent = vi.fn()
    render(
      <RawMarkdownEditor
        content={'# Initial'}
        language="markdown"
        theme="light"
        cursor={{ selectionStart: 9, selectionEnd: 9 }}
        scrollTop={0}
        onChangeContent={onChangeContent}
        onUpdateViewState={vi.fn()}
      />
    )

    const editor = screen.getByTestId('document-editor')
    editor.focus()
    await user.keyboard('!')

    expect(onChangeContent).toHaveBeenCalled()
    expect(onChangeContent.mock.calls[onChangeContent.mock.calls.length - 1][0]).toBe('# Initial!')
  })

  it('supports inserting, adding/deleting rows & columns, and formatting tables via Raw Table Toolbar', async () => {
    const user = userEvent.setup()
    let currentDoc = '# Notes\n\n| Name | Role |\n| :--- | ---: |\n| Alice | Admin |'
    const onChangeContent = vi.fn((next: string) => {
      currentDoc = next
    })
    const onUpdateViewState = vi.fn()

    const { rerender } = render(
      <RawMarkdownEditor
        content={currentDoc}
        language="markdown"
        theme="light"
        cursor={{ selectionStart: currentDoc.indexOf('Alice'), selectionEnd: currentDoc.indexOf('Alice') }}
        scrollTop={0}
        showTableToolbar
        onChangeContent={onChangeContent}
        onUpdateViewState={onUpdateViewState}
      />
    )

    const toolbar = screen.getByRole('toolbar', { name: 'Raw 표 편집 툴바' })

    await user.click(within(toolbar).getByRole('button', { name: '행 아래 추가' }))
    expect(onChangeContent).toHaveBeenCalledTimes(1)
    expect(currentDoc).toBe(
      [
        '# Notes',
        '',
        '| Name  |  Role |',
        '| :---- | ----: |',
        '| Alice | Admin |',
        '|       |       |'
      ].join('\n')
    )

    // Re-render with updated doc & cursor inside table
    rerender(
      <RawMarkdownEditor
        content={currentDoc}
        language="markdown"
        theme="light"
        cursor={{ selectionStart: currentDoc.indexOf('Admin'), selectionEnd: currentDoc.indexOf('Admin') }}
        scrollTop={0}
        showTableToolbar
        onChangeContent={onChangeContent}
        onUpdateViewState={onUpdateViewState}
      />
    )

    await user.click(within(toolbar).getByRole('button', { name: '열 우 추가' }))
    expect(currentDoc).toBe(
      [
        '# Notes',
        '',
        '| Name  |  Role | 열  |',
        '| :---- | ----: | --- |',
        '| Alice | Admin |     |',
        '|       |       |     |'
      ].join('\n')
    )

    rerender(
      <RawMarkdownEditor
        content={currentDoc}
        language="markdown"
        theme="light"
        cursor={{ selectionStart: currentDoc.indexOf('Admin'), selectionEnd: currentDoc.indexOf('Admin') }}
        scrollTop={0}
        showTableToolbar
        onChangeContent={onChangeContent}
        onUpdateViewState={onUpdateViewState}
      />
    )

    await user.click(within(toolbar).getByRole('button', { name: '현재 열 삭제' }))
    expect(currentDoc).toBe(
      [
        '# Notes',
        '',
        '| Name  | 열  |',
        '| :---- | --- |',
        '| Alice |     |',
        '|       |     |'
      ].join('\n')
    )
  })

  it('tracks table cursor state when showTableToolbar flips from false to true on an open editor', async () => {
    const tableDoc = [
      'Intro',
      '',
      '| Name  | Role  |',
      '| ----- | ----- |',
      '| Alice | Admin |'
    ].join('\n')
    let currentDoc = tableDoc
    const onChangeContent = vi.fn((next: string) => {
      currentDoc = next
    })

    const { rerender } = render(
      <RawMarkdownEditor
        content={currentDoc}
        language="markdown"
        theme="light"
        cursor={{ selectionStart: 0, selectionEnd: 0 }}
        scrollTop={0}
        showTableToolbar={false}
        onChangeContent={onChangeContent}
        onUpdateViewState={vi.fn()}
      />
    )
    expect(screen.queryByRole('toolbar', { name: 'Raw 표 편집 툴바' })).not.toBeInTheDocument()

    // Simulate renaming an open .txt tab to .md while editor remains mounted
    rerender(
      <RawMarkdownEditor
        content={currentDoc}
        language="markdown"
        theme="light"
        cursor={{ selectionStart: 0, selectionEnd: 0 }}
        scrollTop={0}
        showTableToolbar
        onChangeContent={onChangeContent}
        onUpdateViewState={vi.fn()}
      />
    )

    const toolbar = screen.getByRole('toolbar', { name: 'Raw 표 편집 툴바' })
    const addRowBelowBtn = within(toolbar).getByRole('button', { name: '행 아래 추가' })
    expect(addRowBelowBtn).toBeDisabled()

    // Move cursor into table via editor update listener (without prop-driven cursor change)
    const adminOffset = currentDoc.indexOf('Admin')
    const view = EditorView.findFromDOM(screen.getByTestId('document-editor'))!
    view.dispatch({ selection: { anchor: adminOffset } })

    await waitFor(() => {
      expect(addRowBelowBtn).toBeEnabled()
    })

    // Flipping showTableToolbar off then back on while cursor sits inside the table also stays synced
    rerender(
      <RawMarkdownEditor
        content={currentDoc}
        language="markdown"
        theme="light"
        cursor={{ selectionStart: adminOffset, selectionEnd: adminOffset }}
        scrollTop={0}
        showTableToolbar={false}
        onChangeContent={onChangeContent}
        onUpdateViewState={vi.fn()}
      />
    )
    expect(screen.queryByRole('toolbar', { name: 'Raw 표 편집 툴바' })).not.toBeInTheDocument()

    rerender(
      <RawMarkdownEditor
        content={currentDoc}
        language="markdown"
        theme="light"
        cursor={{ selectionStart: adminOffset, selectionEnd: adminOffset }}
        scrollTop={0}
        showTableToolbar
        onChangeContent={onChangeContent}
        onUpdateViewState={vi.fn()}
      />
    )
    expect(
      within(screen.getByRole('toolbar', { name: 'Raw 표 편집 툴바' })).getByRole('button', {
        name: '행 아래 추가'
      })
    ).toBeEnabled()
  })

  it('handles CRLF content and EOF cursor safely without RangeError or spurious resets, preserving CRLF on edits', async () => {
    const user = userEvent.setup()
    const crlfDoc = ['Intro line', '', '| A    | B    |', '| ---- | ---- |', '| Val1 | Val2 |'].join('\r\n')
    const onChangeContent = vi.fn()
    const onUpdateViewState = vi.fn()

    // Cursor passed at crlfDoc.length (> CM6 internal LF length) must not throw RangeError
    const { rerender } = render(
      <RawMarkdownEditor
        content={crlfDoc}
        language="markdown"
        theme="light"
        cursor={{ selectionStart: crlfDoc.length, selectionEnd: crlfDoc.length }}
        scrollTop={0}
        showTableToolbar
        onChangeContent={onChangeContent}
        onUpdateViewState={onUpdateViewState}
      />
    )

    const editorEl = screen.getByTestId('document-editor')
    expect(onChangeContent).not.toHaveBeenCalled()

    // Re-rendering with same CRLF content and an in-table LF offset must not trigger spurious replacement
    const tableCellOffset = crlfDoc.replace(/\r\n/g, '\n').indexOf('Val1')
    rerender(
      <RawMarkdownEditor
        content={crlfDoc}
        language="markdown"
        theme="light"
        cursor={{ selectionStart: tableCellOffset, selectionEnd: tableCellOffset }}
        scrollTop={0}
        showTableToolbar
        onChangeContent={onChangeContent}
        onUpdateViewState={onUpdateViewState}
      />
    )
    expect(onChangeContent).not.toHaveBeenCalled()
    expect(editorEl.getAttribute('data-selection-start')).toBe(String(tableCellOffset))

    // Running a Raw table action preserves CRLF line endings in emitted document content
    const toolbar = screen.getByRole('toolbar', { name: 'Raw 표 편집 툴바' })
    const addRowBelowBtn = within(toolbar).getByRole('button', { name: '행 아래 추가' })
    expect(addRowBelowBtn).toBeEnabled()
    await user.click(addRowBelowBtn)
    expect(onChangeContent).toHaveBeenCalledTimes(1)
    const emitted = onChangeContent.mock.calls[0][0] as string
    expect(emitted).toContain('\r\n')
    expect(emitted.split('\r\n').filter((line) => line.startsWith('|'))).toHaveLength(4)
  })

  it('scrolls to and moves selection to the target heading line on scrollRequest and supports /toc insertion outside code fences', async () => {
    const user = userEvent.setup()
    const doc = [
      '# Title',
      '',
      '/toc',
      '',
      '```md',
      '/toc',
      '```',
      '',
      '## Details',
      'Body text'
    ].join('\n')
    const onChangeContent = vi.fn()
    const onUpdateViewState = vi.fn()

    const { rerender } = render(
      <RawMarkdownEditor
        content={doc}
        language="markdown"
        theme="light"
        cursor={{ selectionStart: 0, selectionEnd: 0 }}
        scrollTop={0}
        showTableToolbar
        onChangeContent={onChangeContent}
        onUpdateViewState={onUpdateViewState}
      />
    )

    // Scroll request targets 1-based line 9 ("## Details")
    rerender(
      <RawMarkdownEditor
        content={doc}
        language="markdown"
        theme="light"
        cursor={{ selectionStart: 0, selectionEnd: 0 }}
        scrollTop={0}
        showTableToolbar
        scrollRequest={{ line: 9, nonce: 1 }}
        onChangeContent={onChangeContent}
        onUpdateViewState={onUpdateViewState}
      />
    )

    const editorEl = screen.getByTestId('document-editor')
    const targetOffset = doc.indexOf('## Details')
    await waitFor(() => {
      expect(editorEl.getAttribute('data-selection-start')).toBe(String(targetOffset))
    })

    // Triggering Enter on /toc inside a fenced code block does NOT insert a TOC block
    const view = EditorView.findFromDOM(editorEl)!
    const insideFencePos = doc.indexOf('/toc', doc.indexOf('```md')) + 4
    view.dispatch({ selection: { anchor: insideFencePos } })
    fireEvent.keyDown(editorEl, { key: 'Enter' })

    const emittedInsideFence = onChangeContent.mock.calls.at(-1)?.[0] as string
    expect(emittedInsideFence).not.toContain('<!-- toc -->')

    // Re-render original doc and trigger Enter on /toc outside fence
    onChangeContent.mockClear()
    rerender(
      <RawMarkdownEditor
        content={doc}
        language="markdown"
        theme="light"
        cursor={{ selectionStart: doc.indexOf('/toc') + 4, selectionEnd: doc.indexOf('/toc') + 4 }}
        scrollTop={0}
        showTableToolbar
        onChangeContent={onChangeContent}
        onUpdateViewState={onUpdateViewState}
      />
    )

    fireEvent.keyDown(editorEl, { key: 'Enter' })
    expect(onChangeContent).toHaveBeenCalled()
    const afterSlashToc = onChangeContent.mock.calls.at(-1)?.[0] as string
    expect(afterSlashToc).toContain('<!-- toc -->')
    expect(afterSlashToc).toContain('- [Details](#details)')

    // Toolbar button also inserts/updates TOC when a new heading is added
    onChangeContent.mockClear()
    const docWithAddedHeading = `${afterSlashToc}\n\n### New Section`
    rerender(
      <RawMarkdownEditor
        content={docWithAddedHeading}
        language="markdown"
        theme="light"
        cursor={{ selectionStart: 0, selectionEnd: 0 }}
        scrollTop={0}
        showTableToolbar
        onChangeContent={onChangeContent}
        onUpdateViewState={onUpdateViewState}
      />
    )
    const toolbar = screen.getByRole('toolbar', { name: 'Raw 표 편집 툴바' })
    await user.click(within(toolbar).getByRole('button', { name: '목차 삽입' }))
    expect(onChangeContent).toHaveBeenCalledTimes(1)
    expect(onChangeContent.mock.calls[0][0]).toContain('<!-- toc -->')
    expect(onChangeContent.mock.calls[0][0]).toContain('- [New Section](#new-section)')
  })
})
