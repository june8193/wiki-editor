    fireEvent.wheel(scroller)
    scrollTopSpy.current = 98
    fireEvent.scroll(scroller)
    expect(onActiveHeadingChange).toHaveBeenLastCalledWith({
      headingIndex: 1,
      isUserScroll: true
    })

